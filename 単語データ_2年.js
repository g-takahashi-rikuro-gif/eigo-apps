// 「まとめ」は全単元の単語を重複なしで集めたもの
function dedupeWords(lists) {
  const seen = new Set(), result = [];
  lists.forEach(list => {
    list.forEach(w => {
      if (!seen.has(w.en)) { seen.add(w.en); result.push(w); }
    });
  });
  return result;
}
